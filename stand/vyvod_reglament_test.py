def emu(path, data=None):
    req = urllib.request.Request(EMU + path, json.dumps(data).encode() if data is not None else None,
                                 {'Content-Type': 'application/json'})
    return json.load(urllib.request.urlopen(req))


def run(name, bsl):
    out = HERE / f'{name}.result.json'
    task = {'out': str(out), 'толькоЧтение': False, 'прерыватьПоОшибке': True,
            'команды': [{'тип': 'код', 'имя': name, 'код': bsl.strip().splitlines()}]}
    path = HERE / f'{name}.json'
    path.write_text(json.dumps(task, ensure_ascii=False, indent=1), encoding='utf-8')
    subprocess.run(['powershell', '-NoProfile', '-File', RUNNER, '-Task', str(path), '-Base', BASE, '-User', 'Тест',
                    '-TimeoutSec', '600'], capture_output=True)
    r = json.load(open(out, encoding='utf-8-sig'), strict=False)['результаты'][0]
    print(f'--- {name}: {r["статус"]}\n' + json.dumps(r.get('результат') or r.get('ошибка'), ensure_ascii=False, indent=1))
    if r['статус'] != 'ок':
        raise SystemExit(1)
    return r['результат']


